# Sorting a list
# Ascending   
# Descending 
fruits = ["Apple", "Mango", "Bananna","Cherry"]
print(fruits)

# Sorting a list
fruits.sort()
print( "Ascending order:",fruits)    # By Default it is in a ascending

fruits.sort(reverse=True)   # Sorted in descending 
print( "Descending Order :",fruits)

# Reverse the list
fruits.reverse()
print( "Reverse a list :" ,fruits)