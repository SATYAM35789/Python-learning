# Numeric data type 
# 1. int :- Whole,integer no. like 45, 567, -234
# 2. Float :- Decimal NO. -> 2.5 , -1.8
# 3. complex :-1+3j, 56+450j 

# Text data type :- 
# string :- sequence of characters , enclose ' ' or " " example 'satya' "name"

# Boolean data type : boolean values -> True and False

# Sequence data type
# list :- sequence of integers, strings ex [1,2,3,4] ['satyam' 'monu' 'sidhh'] the values are 
# unique and can be change
# Tuple :- sequence of items , items can duplicate, cann't be changed ( 1,2,3,3,4)

#  Mapping data types 
# 1. Dictionary data type :- key-value pairs have been stored 
#  example student ={
#         name:xyz
#         rollno:123       
#       }

# 2. set data type :- 
#  unordered collection of unique items ex fruits= { "apple","bananna","cherry"}

# none data type :- represents null value

